#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
RX="firmware/ESP32_1/ESP32_1.ino"
PINS="firmware/ESP32_1/src/HardwarePins.h"
ETH="firmware/common/EthernetStatus.h"
grep -Fq '#include <SPI.h>' "$RX"
grep -Fq '#include <Ethernet.h>' "$RX"
grep -Fq 'HwcPins::Esp32_1::W5500_RST' "$RX"
grep -Fq 'SPI.begin(sck_, miso_,' "$ETH"
grep -Fq 'Ethernet.init(cs_)' "$ETH"
grep -Fq 'Ethernet.begin(mac, 2000, 250)' "$ETH"
grep -Fq 'xTaskCreatePinnedToCore(taskEntry' "$ETH"
grep -Fq 'publishEthernetWaterStatus();' "$RX"
grep -Fq 'ethernetStatusServer.accept()' "$ETH"
grep -Fq 'if (strcmp(request.method, "GET") != 0)' "$ETH"
grep -Fq 'if (!ethernetCredentialsMatch(request))' "$ETH"
grep -Fq 'constexpr uint8_t W5500_CS   = 27;' "$PINS"
grep -Fq 'constexpr uint8_t W5500_RST  = 26;' "$PINS"
! grep -Eq 'EthernetUDP|WiFiUDP|peerUdp|PeerStatus' "$RX"
echo 'PASS: ESP32 #1 W5500 task and authenticated read-only endpoint are integrated'
