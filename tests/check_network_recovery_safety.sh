#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
RX="firmware/ESP32_1/ESP32_1.ino"
TX="firmware/ESP32_2/ESP32_2.ino"
grep -Fq 'WiFi.mode(keepStation ? WIFI_AP_STA : WIFI_AP);' "$RX"
grep -Fq 'WiFi.begin(savedWifiSsid.c_str(), savedWifiPassword.c_str());' "$RX"
grep -Fq '>= 15000U' "$RX"
grep -Fq '>= 30000U' "$RX"
grep -Fq 'startConfigAp(true);' "$RX"
grep -Fq 'WebServer webServer(80);' "$RX"
grep -Fq 'ethernetStatus.begin(adminPassword);' "$RX"
! grep -Eq 'WiFiUDP|peerUdp|PeerStatus' "$RX"
grep -Fq 'startEthernet();' "$TX"
grep -Fq 'maintainLocalWifi(now);' "$TX"
grep -Fq 'serviceApActive = WiFi.softAP(localApName.c_str(), localApPassword.c_str());' "$TX"
grep -Fq 'WiFi.enableSTA(true)' "$TX"
grep -Fq 'WiFi.disconnectAsync(false, false);' "$TX"
grep -Fq 'if (wifiReady || ethernetReady)' "$TX"
grep -Fq 'MANAGEMENT_LINK_GRACE_MS = 30000U' "$TX"
grep -Fq 'WiFi.STA.connect(savedWifiSsid.c_str(), savedWifiPassword.c_str())' "$TX"
grep -Fq 'localWebServer.on("/wifi", HTTP_POST, handleLocalWifi);' "$TX"
grep -Fq 'localWebServer.begin()' "$TX"
! grep -Eq 'EthernetUDP|peerUdp|PeerStatus' "$TX"
! grep -Eq 'EthernetServer|EthernetWebServer' "$TX"
echo "PASS: both independent network paths recover locally; no peer transport dependency"
