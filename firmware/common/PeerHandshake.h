#ifndef HWC_PEER_HANDSHAKE_H
#define HWC_PEER_HANDSHAKE_H

#include <stddef.h>
#include <stdint.h>

namespace HWC {

class IPeerReplayStore;

static const size_t PEER_HANDSHAKE_NONCE_SIZE = 16U;
static const size_t PEER_HANDSHAKE_TAG_SIZE = 32U;
static const size_t PEER_HANDSHAKE_MIN_SECRET_SIZE = 32U;

struct PeerHandshakeHello {
    uint8_t initiatorDeviceId;
    uint8_t responderDeviceId;
    uint32_t initiatorBootId;
    uint8_t initiatorNonce[PEER_HANDSHAKE_NONCE_SIZE];
};

struct PeerHandshakeChallenge {
    uint8_t initiatorDeviceId;
    uint8_t responderDeviceId;
    uint32_t initiatorBootId;
    uint32_t responderBootId;
    uint32_t authenticatedReplayFloor;
    uint8_t initiatorNonce[PEER_HANDSHAKE_NONCE_SIZE];
    uint8_t responderNonce[PEER_HANDSHAKE_NONCE_SIZE];
    uint8_t tag[PEER_HANDSHAKE_TAG_SIZE];
};

struct PeerHandshakeFinish {
    uint8_t tag[PEER_HANDSHAKE_TAG_SIZE];
};

// Nonces MUST be generated by a cryptographically secure random source on the
// device (ESP32: esp_random()). This module deliberately does not provide RNG.
bool createPeerHandshakeChallenge(const PeerHandshakeHello& hello,
                                  uint32_t responderBootId,
                                  const uint8_t responderNonce[PEER_HANDSHAKE_NONCE_SIZE],
                                  const uint8_t* secret, size_t secretLength,
                                  PeerHandshakeChallenge& challenge,
                                  uint32_t authenticatedReplayFloor = 0U);

// Initiator verifies responder authentication, creates its proof, and derives
// the session key. Do not use the key until the responder has accepted FINISH.
bool verifyPeerHandshakeChallenge(const PeerHandshakeHello& hello,
                                   const PeerHandshakeChallenge& challenge,
                                   const uint8_t* secret, size_t secretLength,
                                   PeerHandshakeFinish& finish,
                                   uint8_t sessionKey[PEER_HANDSHAKE_TAG_SIZE]);

// Low-level responder verification helper. Prefer PeerHandshakeResponder below for
// application use; this function is stateless and does not itself prevent replay.
bool verifyPeerHandshakeFinish(const PeerHandshakeHello& hello,
                               const PeerHandshakeChallenge& challenge,
                               const PeerHandshakeFinish& finish,
                               const uint8_t* secret, size_t secretLength,
                               uint8_t sessionKey[PEER_HANDSHAKE_TAG_SIZE]);


// Stateful responder wrapper. It pins one pending HELLO/CHALLENGE pair and
// consumes it on the first FINISH attempt, preventing a successful FINISH from
// being accepted twice by this object. The caller must enforce a timeout and
// reject a second HELLO while a challenge is pending.
class PeerHandshakeResponder {
public:
    PeerHandshakeResponder();
    bool begin(uint8_t expectedPeerDeviceId, uint8_t localDeviceId,
               uint32_t localBootId, const PeerHandshakeHello& hello,
               const uint8_t responderNonce[PEER_HANDSHAKE_NONCE_SIZE],
               const uint8_t* secret, size_t secretLength,
               PeerHandshakeChallenge& challenge,
               uint32_t authenticatedReplayFloor = 0U);
    // Preferred receiver entry point: reads the saved floor for the HELLO's
    // peer boot epoch and authenticates it inside CHALLENGE automatically.
    bool beginWithReplayStore(uint8_t expectedPeerDeviceId, uint8_t localDeviceId,
                              uint32_t localBootId, const PeerHandshakeHello& hello,
                              const uint8_t responderNonce[PEER_HANDSHAKE_NONCE_SIZE],
                              const uint8_t* secret, size_t secretLength,
                              IPeerReplayStore& replayStore,
                              PeerHandshakeChallenge& challenge);
    bool acceptFinish(const PeerHandshakeHello& hello,
                      const PeerHandshakeChallenge& challenge,
                      const PeerHandshakeFinish& finish,
                      const uint8_t* secret, size_t secretLength,
                      uint8_t sessionKey[PEER_HANDSHAKE_TAG_SIZE]);
    void cancel();
    bool pending() const;
private:
    PeerHandshakeHello pendingHello_;
    PeerHandshakeChallenge pendingChallenge_;
    bool pending_;
};

} // namespace HWC
#endif
